const {contextBridge,ipcRenderer,webUtils}=require('electron');
contextBridge.exposeInMainWorld('canvasFiles',{
 openProjectFolder:projectPath=>ipcRenderer.invoke('canvas-project:open-folder',projectPath),
 pruneUndoAssets:payload=>ipcRenderer.invoke('canvas-project:prune-undo-assets',payload),
 pinUndoAssets:payload=>ipcRenderer.invoke('canvas-project:pin-undo-assets',payload),
 listReferences:()=>ipcRenderer.invoke('canvas-reference:list'),
 saveReference:payload=>ipcRenderer.invoke('canvas-reference:save',payload),
 importReferences:category=>ipcRenderer.invoke('canvas-reference:import',category),
 categorizeReferences:payload=>ipcRenderer.invoke('canvas-reference:categorize',payload),
 attachReference:payload=>ipcRenderer.invoke('canvas-reference:attach',payload),
 onPrepareClose:callback=>{const listener=()=>callback();ipcRenderer.on('canvas:prepare-close',listener);return()=>ipcRenderer.removeListener('canvas:prepare-close',listener);},
 finishClose:payload=>ipcRenderer.invoke('canvas:finish-close',payload),
 confirmCloseChanges:()=>ipcRenderer.invoke('canvas:confirm-close-changes'),
 openLastProject:()=>ipcRenderer.invoke('canvas-project:open-last'),
 getPathForFile:file=>webUtils.getPathForFile(file),
 loadProjectAsset:payload=>ipcRenderer.invoke('canvas-project:load-asset',payload),
 readProjectJson:source=>ipcRenderer.invoke('canvas-project:read-json',source),
 listProjects:()=>ipcRenderer.invoke('canvas-project:library'),
 manageProject:source=>ipcRenderer.invoke('canvas-project:manage',source),
 openManagedProject:source=>ipcRenderer.invoke('canvas-project:open-managed',source),
 saveManagedProject:payload=>ipcRenderer.invoke('canvas-project:save-managed',payload),
 loadImage:payload=>ipcRenderer.invoke('canvas-image:load',payload),
 importAudio:payload=>ipcRenderer.invoke('canvas-audio:import',payload),
 importVideo:payload=>ipcRenderer.invoke('canvas-video:import',payload),
 importImage:payload=>ipcRenderer.invoke('canvas-image:import',payload),
 pasteImage:bytes=>ipcRenderer.invoke('canvas-image:paste',bytes),
 copyImages:items=>ipcRenderer.invoke('canvas-image:copy-many',items),
 copyImage:source=>ipcRenderer.invoke('canvas-image:copy',source),
 revealImage:payload=>ipcRenderer.invoke('canvas-image:reveal',payload),
 saveImage:url=>ipcRenderer.invoke('canvas-image:save',url),
 previewImage:source=>ipcRenderer.invoke('canvas-image:preview',source)
});
